(function () {
  var SUPPORTED = ['en'].concat(Object.keys(I18N));
  var nodes = document.querySelectorAll('[data-i18n]');
  var metas = document.querySelectorAll('[data-i18n-content]');
  var arias = document.querySelectorAll('[data-i18n-aria]');
  var original = { html: [], content: [], aria: [] };
  nodes.forEach(function (n, i) { original.html[i] = n.innerHTML; });
  metas.forEach(function (n, i) { original.content[i] = n.getAttribute('content'); });
  arias.forEach(function (n, i) { original.aria[i] = n.getAttribute('aria-label'); });

  function pick() {
    try {
      var saved = localStorage.getItem('lang');
      if (saved && SUPPORTED.indexOf(saved) > -1) return saved;
    } catch (e) {}
    var prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en'];
    for (var i = 0; i < prefs.length; i++) {
      var code = String(prefs[i]).toLowerCase().split('-')[0];
      if (SUPPORTED.indexOf(code) > -1) return code;
    }
    return 'en';
  }

  function apply(lang) {
    var d = I18N[lang] || {};
    nodes.forEach(function (n, i) { var v = d[n.getAttribute('data-i18n')]; n.innerHTML = v != null ? v : original.html[i]; });
    metas.forEach(function (n, i) { var v = d[n.getAttribute('data-i18n-content')]; n.setAttribute('content', v != null ? v : original.content[i]); });
    arias.forEach(function (n, i) { var v = d[n.getAttribute('data-i18n-aria')]; n.setAttribute('aria-label', v != null ? v : original.aria[i]); });
    document.documentElement.lang = lang;
    if (select) select.value = lang;
  }

  var select = document.getElementById('lang');
  if (select) select.addEventListener('change', function () {
    try { localStorage.setItem('lang', select.value); } catch (e) {}
    apply(select.value);
  });
  apply(pick());
})();
